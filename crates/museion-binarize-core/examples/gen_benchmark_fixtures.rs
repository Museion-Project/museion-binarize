//! Regenerates the committed `test-data/benchmark/synthetic-v1/` suite
//! from `benchmark_fixtures.rs`'s deterministic generator.
//!
//! ```text
//! cargo run -p museion-binarize-core --example gen_benchmark_fixtures -- <dir>
//! ```
//!
//! Rerunning this against the same generator version must reproduce the
//! committed files byte-for-byte for the PNGs it writes (verified by the
//! ordinary test
//! `benchmark_fixture_suite_regenerates_byte_identical_pngs` in
//! `tests/benchmark_suite.rs`, which calls the same generator functions
//! directly rather than shelling out to this binary).

use std::path::Path;
use std::process::ExitCode;

use image::{GrayImage, Luma};
use museion_binarize_core::benchmark::dataset::{
    DatasetManifest, PageManifest, DATASET_SCHEMA, DATASET_SCHEMA_VERSION,
};
use museion_binarize_core::benchmark::mask_io::GroundTruthPolarity;
use museion_binarize_core::benchmark::roi::Roi;
use museion_binarize_core::benchmark_fixtures::{self, ALL_CATEGORIES};
use museion_binarize_core::bilevel::BinaryMask;

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(message) => {
            eprintln!("gen_benchmark_fixtures: {message}");
            ExitCode::FAILURE
        }
    }
}

fn ground_truth_png(mask: &BinaryMask) -> GrayImage {
    let mut img = GrayImage::new(mask.width, mask.height);
    for y in 0..mask.height {
        for x in 0..mask.width {
            // BlackIsZero convention: black (foreground) -> 0, white -> 255.
            let value = if mask.get(x, y) { 0u8 } else { 255u8 };
            img.put_pixel(x, y, Luma([value]));
        }
    }
    img
}

fn run() -> Result<(), String> {
    let Some(dir) = std::env::args().nth(1) else {
        return Err("usage: gen_benchmark_fixtures <dir>".to_string());
    };
    let dir = Path::new(&dir);
    let input_dir = dir.join("input");
    let gt_dir = dir.join("ground-truth");
    std::fs::create_dir_all(&input_dir).map_err(|e| e.to_string())?;
    std::fs::create_dir_all(&gt_dir).map_err(|e| e.to_string())?;

    let mut pages = Vec::new();
    for category in ALL_CATEGORIES {
        let fixture = benchmark_fixtures::generate(category);
        let id = category.id();

        let input_path = input_dir.join(format!("{id}.png"));
        fixture
            .input
            .save(&input_path)
            .map_err(|e| format!("could not write {}: {e}", input_path.display()))?;

        let gt_path = gt_dir.join(format!("{id}.png"));
        ground_truth_png(&fixture.ground_truth)
            .save(&gt_path)
            .map_err(|e| format!("could not write {}: {e}", gt_path.display()))?;

        let rois = fixture
            .rois
            .into_iter()
            .map(|(roi_id, x, y, width, height, tag)| Roi {
                id: roi_id,
                x,
                y,
                width,
                height,
                tag,
            })
            .collect();

        pages.push(PageManifest {
            id: id.to_string(),
            input: format!("input/{id}.png"),
            ground_truth: format!("ground-truth/{id}.png"),
            category: id.to_string(),
            tags: vec![],
            notes: None,
            source_url: None,
            rights_holder: None,
            expected_width: Some(fixture.ground_truth.width),
            expected_height: Some(fixture.ground_truth.height),
            rois,
        });
    }

    let manifest = DatasetManifest {
        schema: DATASET_SCHEMA.to_string(),
        schema_version: DATASET_SCHEMA_VERSION.to_string(),
        id: "synthetic-document-v1".to_string(),
        title: "Synthetic document binarization benchmark, v1".to_string(),
        description: "Deterministic, procedurally generated benchmark pages covering \
            common binarization stress cases (faint/small text, noise, uneven \
            background, broken/thick strokes, mixed text and rule lines, dense \
            apparatus-like density, and polytonic-diacritic-like stress shapes). \
            Contains no real text, no font-rendered glyphs, and no copyrighted \
            material of any kind."
            .to_string(),
        license: "CC0-1.0".to_string(),
        provenance: "Generated by museion-binarize-core's benchmark_fixtures module \
            (crates/museion-binarize-core/src/benchmark_fixtures.rs) via this example \
            binary (examples/gen_benchmark_fixtures.rs). Every shape is drawn \
            procedurally from fixed geometric rules; no font, scan, or third-party \
            image was used."
            .to_string(),
        ground_truth_method: "Ground truth is the exact procedural shape drawn before \
            any degradation is applied; it is never produced by running Museion \
            Binarize's own binarization pipeline (which would make the benchmark \
            circular)."
            .to_string(),
        ground_truth_polarity: GroundTruthPolarity::BlackIsZero,
        ground_truth_creator: Some("procedural generator".to_string()),
        ground_truth_review_status: Some(
            "not applicable (procedurally exact, not manually annotated)".to_string(),
        ),
        ground_truth_review_method: None,
        pages,
    };

    let toml_text = toml::to_string_pretty(&manifest).map_err(|e| e.to_string())?;
    let manifest_path = dir.join("dataset.toml");
    std::fs::write(&manifest_path, toml_text)
        .map_err(|e| format!("could not write {}: {e}", manifest_path.display()))?;

    eprintln!("wrote {} pages to {}", ALL_CATEGORIES.len(), dir.display());
    Ok(())
}
